// bukan angka statis yang gampang basi kalau ada penambahan/penghapusan data.
export const kategoriBerita = Object.values(
  beritaList.reduce((acc, item) => {
    if (!acc[item.kategoriSlug]) {
      acc[item.kategoriSlug] = {
        nama: item.kategori,
        slug: item.kategoriSlug,
        jumlah: 0,
      };
    }
    acc[item.kategoriSlug].jumlah += 1;
    return acc;
  }, {})
);

