// Helper lookup — memudahkan halaman detail berita (mis. /:slug) mengambil
// satu item tanpa harus filter manual berulang kali di tiap page.
export function getBeritaBySlug(slug) {
  return beritaList.find((item) => item.slug === slug) || null;
}

export function getBeritaByKategori(kategoriSlug) {
  return beritaList.filter((item) => item.kategoriSlug === kategoriSlug);
}
